def digest(data):
    return {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}


class PackageTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(msix, "Scriblark MSIX qualification is not implemented")
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name).resolve()
        self.source = self.root / "source"
        self.release = self.root / "release"
        self.commit = "a" * 40
        self.inventory = self.root / "inputs.json"
        self.startup = self.root / "startup.json"
        actual = Path(__file__).resolve().parents[2]
        for relative in msix.SOURCE_FILES:
            target = self.source / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes((actual / relative).read_bytes())
        for relative in msix.REQUIRED_RELEASE_FILES:
            target = self.release / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            original = msix.SOURCE_COPIES.get(relative)
            target.write_bytes(
                (self.source / original).read_bytes()
                if original
                else (relative + " native fixture").encode()
            )
        # Use the actual retained originals, not strings generated by the
        # validator. Native inventory below observes these additional files.
        shutil.copytree(actual / "Release/notice-supplement/originals",
                        self.source / "Release/notice-supplement/originals")
        shutil.copytree(actual / "Release/notice-supplement/originals",
                        self.release / "share/inkquay/licenses/supplement/originals")
        self.artwork = self.source / "ui/pixmaps/com.trieflow.inkquay.png"
        self.native = self.source / "build/inkquay-windows-inventory.json"
        self.native.parent.mkdir(parents=True)
        files = msix.inventory_tree(self.release)
        prepared = json.loads((self.source / "Release/notice-supplement/SOURCE-INPUTS.json").read_text())
        self.owner = prepared["nativeOwners"][0]["package"]
        self.owner_version = prepared["nativeOwners"][0]["version"]
        rows = [
            {
                "path": name,
                **record,
                "package": self.owner,
                "packageVersion": self.owner_version,
            }
            for name, record in files.items()
        ]
        for row in rows:
            if row["path"] in ("bin/Scriblark.exe", "bin/Scriblark-wrapper.exe"):
                del row["package"]
                del row["packageVersion"]
        self.native.write_text(
            json.dumps(
                {
                    "schemaVersion": 3,
                    "sourceCommit": self.commit,
                    "platform": "win32",
                    "msystem": "MINGW64",
                    "packages": {self.owner: self.owner_version},
                    "files": rows,
                    "builtApplication": {"sha256": files["bin/Scriblark.exe"]["sha256"]},
                    "builtWrapper": {
                        "sha256": files["bin/Scriblark-wrapper.exe"]["sha256"]
                    },
                    "licenseAuditComplete": False,
                }
            )
        )
        self.refresh()

    def refresh(self):
        d = msix.create_input_inventory(self.release, self.source, self.commit)
        self.inventory.write_text(json.dumps(d))
        self.startup.write_text(
            json.dumps(
                {
                    "source_commit": self.commit,
                    "windows_native_startup": True,
                    "window_title": "Unsaved Document - Scriblark",
                    "executable_sha256": d["files"]["bin/Scriblark.exe"]["sha256"],
                    "package_inventory_sha256": digest(self.inventory.read_bytes())[
                        "sha256"
                    ],
                }
            )
        )

    def stage(self):
        return msix.stage_release(
            self.release,
            self.artwork,
            self.root / "stage",
            self.commit,
            self.inventory,
            self.startup,
            self.source,
        )

