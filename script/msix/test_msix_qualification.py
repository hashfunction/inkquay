    def test_rehashed_stage_cannot_omit_or_change_original_supplements(self):
        prefix = "share/inkquay/licenses/supplement/"
        examples = (
            "originals/notice-supplement/mingw-w64-gmp/gmp-6.3.0/COPYING",
            "originals/cargo-inputs/upstream-notices/mutants-0.0.4/LICENSE",
            "originals/rust-runtime-notices/LICENSE-MIT",
            "SOURCE-INPUTS.json",
        )
        native_original = self.native.read_bytes()
        for relative in examples:
            name = prefix + relative
            target = self.release / name
            original = target.read_bytes()
            for replacement in (None, b"generic replacement notice"):
                with self.subTest(path=relative, missing=replacement is None):
                    if replacement is None:
                        target.unlink()
                    else:
                        target.write_bytes(replacement)
                    native = json.loads(native_original)
                    native["files"] = [row for row in native["files"] if row["path"] != name]
                    if replacement is not None:
                        native["files"].append({"path": name, **digest(replacement)})
                    self.native.write_text(json.dumps(native))
                    with self.assertRaisesRegex(ValueError, "Missing|notice/artwork"):
                        msix.create_input_inventory(self.release, self.source, self.commit)
                    target.write_bytes(original)
        self.native.write_bytes(native_original)

    def test_notice_index_requires_complete_unique_safe_exact_originals(self):
        index_path = self.source / "Release/notice-supplement/NOTICE-INDEX.json"
        original = index_path.read_bytes()
        for kind in ("missing-row", "duplicate", "traversal", "wrong-hash"):
            with self.subTest(kind=kind):
                index = json.loads(original)
                if kind == "missing-row":
                    index["files"].pop()
                    index["fileCount"] -= 1
                elif kind == "duplicate":
                    index["files"].append(dict(index["files"][0]))
                    index["fileCount"] += 1
                elif kind == "traversal":
                    index["files"][0]["path"] = "originals/../../outside"
                else:
                    index["files"][0]["sha256"] = "0" * 64
                index_path.write_text(json.dumps(index))
                with self.assertRaises(ValueError):
                    msix.copy_notice_supplement(self.source, self.root / kind)
                self.assertFalse((self.root / kind).exists())
        index_path.write_bytes(original)

    def test_notice_copy_rejects_changed_missing_or_linked_source_before_output(self):
        target = self.source / "Release/notice-supplement/originals/rust-runtime-notices/LICENSE-MIT"
        original = target.read_bytes()
        for kind in ("changed", "missing"):
            with self.subTest(kind=kind):
                if kind == "changed":
                    target.write_bytes(b"substituted source notice")
                else:
                    target.unlink()
                with self.assertRaises(ValueError):
                    msix.copy_notice_supplement(self.source, self.root / kind)
                self.assertFalse((self.root / kind).exists())
                target.write_bytes(original)
        outside = self.root / "outside-notice"
        outside.write_bytes(original)
        target.unlink()
        try:
            target.symlink_to(outside)
        except OSError as error:
            self.skipTest(f"Host cannot create source symlink: {error}")
        with self.assertRaisesRegex(ValueError, "Symlink/reparse"):
            msix.copy_notice_supplement(self.source, self.root / "linked")
        self.assertFalse((self.root / "linked").exists())
        self.assertEqual(outside.read_bytes(), original)

    def test_actual_notice_copy_command_preserves_all_bytes_and_prior_destination(self):
        actual = Path(__file__).resolve().parents[2]
        commands = [line for line in (actual / "windows-setup/package.sh").read_text().splitlines()
                    if line.startswith('python "$script_dir/../script/msix/copy_notice_supplement.py"')]
        self.assertEqual(len(commands), 1, "Actual Windows staging must invoke the checked notice copy")
        stage = self.root / "notice stage with spaces"
        stage.mkdir()
        unrelated = stage / "existing.txt"
        unrelated.write_bytes(b"preserve unrelated content")
        if sys.platform == "win32":
            bash = Path(sys.executable).resolve().parents[2] / "usr/bin/bash.exe"
            self.assertTrue(bash.is_file(), "Expected the qualified MSYS2 bash")
            setup = 'script_dir=$(cygpath -u "$1"); setup_dir=$(cygpath -u "$2"); python_executable=$(cygpath -u "$3"); '
        else:
            bash = "bash"
            setup = 'script_dir=$1; setup_dir=$2; python_executable=$3; '
        command = [str(bash), "-c", setup + commands[0].replace("python ", '"$python_executable" ', 1),
                   "notice-copy", str(actual / "windows-setup"), str(stage), sys.executable]
        subprocess.run(command, check=True, capture_output=True, text=True)
        expected = msix.inventory_tree(actual / "Release/notice-supplement")
        copied = stage / "share/inkquay/licenses/supplement"
        self.assertEqual(msix.inventory_tree(copied), expected)
        empty = copied / "originals/notice-supplement/mingw-w64-djvulibre/djvulibre-3.5.30/AUTHORS"
        self.assertEqual(empty.read_bytes(), b"")
        source_index = json.loads((copied / "SOURCE-INPUTS.json").read_text())
        self.assertEqual(source_index["sourceUrl"], "https://scriblark.trieflow.com/source")
        self.assertEqual(len(source_index["nativeOwners"]), 66)
        self.assertEqual(len(source_index["cargo"]["sources"]), 359)
        rerun = subprocess.run(command, capture_output=True, text=True)
        self.assertNotEqual(rerun.returncode, 0)
        self.assertIn("preserving prior bytes", rerun.stderr)
        self.assertEqual(msix.inventory_tree(copied), expected)
        self.assertEqual(unrelated.read_bytes(), b"preserve unrelated content")

    def test_current_mingw64_winpthread_owner_requires_exact_retained_version(self):
        # Run 34685959483 stopped on this actual owner/version before any
        # installed application test. The file contents here remain fixtures.
        package = "mingw-w64-x86_64-libwinpthread"
        current = "14.0.0.r375.g9c1abbbf5-1"
